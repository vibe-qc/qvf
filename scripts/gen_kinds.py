#!/usr/bin/env python3
"""Generate the schema-driven tables of the QVF toolkit.

The JSON Schema (``spec/qvf_manifest.schema.json``) is the single source of
truth for the QVF contract. This script reads it, together with
``registry.json`` (canonical kind order, readable versions) and the finding
code table of the specification's Appendix B, and writes:

* ``cpp/include/qvf/kinds_generated.hpp`` -- ``namespace qvf::gen``: the
  ``KindInfo`` / ``RoleInfo`` tables, the canonical kinds, the payload
  definition of each ``(kind, role)``, the ``Unit`` enum with
  ``unit_name`` / ``parse_unit``, the finding codes and the schema ``$id``.
* ``cpp/include/qvf/kinds/all.hpp`` -- concrete typed payload records and
  canonical kind encoders/decoders, rendered by ``gen_typed_kinds.py``.
* ``cpp/include/qvf/c_kinds_generated.h`` -- canonical C writer entry points.
* ``cpp/src/qvf_schema_table.hpp`` -- the compiled schema: a compact
  instruction table that ``cpp/src/qvf_schema_check.hpp`` interprets to check
  ``manifest.json`` and every JSON member payload without a JSON Schema
  engine.
* ``js/src/schemaTable.ts`` -- the same instruction table for the
  TypeScript interpreter ``js/src/schemaCheck.ts``.
* ``python/qvf/_kinds.py`` -- the same kind, unit, payload-definition and
  finding-code tables for the Python reference implementation.
* ``docs/kinds.md`` -- the kind catalogue: members, section fields, payload
  fields, fixed units and a conformance-corpus example of every canonical
  kind, rendered by ``gen_kind_docs.py``.

Usage (from anywhere; standard library only)::

    python3 scripts/gen_kinds.py           # (re)write every generated file
    python3 scripts/gen_kinds.py --check   # exit 1 if a generated file is stale

The output is deterministic: no timestamps, and every table follows the order
of the schema (or of ``registry.json`` for the canonical kinds), so
regenerating an unchanged schema reproduces the committed files byte for
byte. Run it after every schema change, then ``python3 scripts/amalgamate.py``.

Two small tables below are inputs, not outputs, because the schema cannot say
them: ``PAYLOAD_DEFS`` (which ``$defs`` entry specifies the JSON payload of a
section kind's member: payload definitions are archive members, so nothing in
the manifest ``$ref``s them) and ``LEGACY_CANONICAL`` (the unit name each
deprecated spelling stands for). The generator refuses a schema that defines
a ``*Payload`` definition no row of ``PAYLOAD_DEFS`` names, a legacy spelling
without a mapping, or a JSON Schema keyword outside the supported subset, so a
schema change can never be silently left unchecked by the generated checkers.

License: Apache-2.0.
"""

