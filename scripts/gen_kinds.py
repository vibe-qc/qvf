def flatten_regexes(c: SchemaCompiler):
    """The compiled patterns as flat tables: programs [(source, first op,
    count)], ops [(name, x, y)] and code point ranges [lo, hi, ...]; identical
    range lists are stored once."""
    programs: list[tuple[str, int, int]] = []
    rx_ops: list[tuple[str, int, int]] = []
    ranges: list[int] = []
    range_lists: dict[tuple, int] = {}
    for src, prog in zip(c.regexes.items, c.rx_programs):
        programs.append((src, len(rx_ops), len(prog)))
        for op in prog:
            if op[0] in ("Class", "NotClass"):
                key = tuple(op[1])
                if key not in range_lists:
                    range_lists[key] = len(ranges) // 2
                    for lo, hi in key:
                        ranges.extend([lo, hi])
                rx_ops.append((op[0], range_lists[key], len(key)))
            elif op[0] == "Split":
                rx_ops.append((op[0], op[1], op[2]))
            elif op[0] == "Jump":
                rx_ops.append((op[0], op[1], 0))
            else:
                rx_ops.append((op[0], 0, 0))
    return programs, rx_ops, ranges


# --- C++: qvf_schema_table.hpp -----------------------------------------------------

def _op_comment(c: SchemaCompiler, op: tuple) -> str:
    """A short comment naming an op (never ending in a backslash, which would
    continue a C++ line comment)."""
    return _op_text(c, op).rstrip("\\")


def _op_text(c: SchemaCompiler, op: tuple) -> str:
    name = OPCODES[op[0]][0]
    _, x, y, _ = op
    if name == "Properties":
        names = [c.strings.items[c.pairs[x + 2 * i]] for i in range(y)]
        text = ", ".join(names)
        return f"properties: {text[:60]}{'...' if len(text) > 60 else ''}"
    if name == "Required":
        text = ", ".join(c.strings.items[c.lists[x + i]] for i in range(y))
        return f"required: {text[:60]}{'...' if len(text) > 60 else ''}"
    if name == "Ref":
        return f"$ref {c.node_origin[x]}"
    if name in ("Const",):
        return f"const {c.values.items[x][:60]}"
    if name == "Pattern":
        return f"pattern {c.regexes.items[x]}"
    return name[0].lower() + name[1:]


