class _Pool:
    """Interned values with stable first-seen indices."""

    def __init__(self) -> None:
        self.items: list[Any] = []
        self._index: dict[Any, int] = {}

    def add(self, key: Any, value: Any = None) -> int:
        if key not in self._index:
            self._index[key] = len(self.items)
            self.items.append(key if value is None else value)
        return self._index[key]


# --- regular expressions --------------------------------------------------------
#
# The subset of ECMA-262 the generated matchers implement: literals, `.`,
# character classes with ranges and negation, the escapes \d \D \w \W \s \S
# \0 \t \n \v \f \r \xHH \uHHHH \u{H...} and escaped punctuation, groups
# `(...)` and `(?:...)`, alternation, the anchors ^ and $ (not multiline),
# and the quantifiers * + ? {n} {n,} {n,m} (greedy or lazy: the matchers only
# answer "does it match anywhere", so both are the same). JSON Schema
# patterns are unanchored searches. Backreferences, lookaround, word
# boundaries, named groups and flags are refused.

_LINE_TERMINATORS = [(0x0A, 0x0A), (0x0D, 0x0D), (0x2028, 0x2029)]
_DIGIT = [(0x30, 0x39)]
_WORD = [(0x30, 0x39), (0x41, 0x5A), (0x5F, 0x5F), (0x61, 0x7A)]
_SPACE = [(0x09, 0x0D), (0x20, 0x20), (0xA0, 0xA0), (0x1680, 0x1680),
          (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F),
          (0x205F, 0x205F), (0x3000, 0x3000), (0xFEFF, 0xFEFF)]
_MAX_CODE_POINT = 0x10FFFF
_MAX_RX_INSTRUCTIONS = 4096


def _merge_ranges(ranges: list[tuple[int, int]]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for lo, hi in sorted(ranges):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def _complement(ranges: list[tuple[int, int]]) -> list[tuple[int, int]]:
    out, nxt = [], 0
    for lo, hi in _merge_ranges(ranges):
        if lo > nxt:
            out.append((nxt, lo - 1))
        nxt = hi + 1
    if nxt <= _MAX_CODE_POINT:
        out.append((nxt, _MAX_CODE_POINT))
    return out


class _RegexParser:
    """Parse a pattern into a small tree: ('class', negated, ranges),
    ('start',), ('end',), ('cat', items), ('alt', branches),
    ('repeat', node, lo, hi-or-None)."""

    def __init__(self, source: str) -> None:
        self.src = source
        self.i = 0

    def fail(self, why: str) -> GenerationError:
        return GenerationError(f"pattern {self.src!r}: {why} (at offset {self.i}); "
                               f"see the supported subset in scripts/gen_kinds.py")

    def peek(self) -> str:
        return self.src[self.i] if self.i < len(self.src) else ""

    def parse(self):
        node = self.alternation()
        if self.i != len(self.src):
            raise self.fail("unbalanced ')'")
        return node

    def alternation(self):
        branches = [self.sequence()]
        while self.peek() == "|":
            self.i += 1
            branches.append(self.sequence())
        return branches[0] if len(branches) == 1 else ("alt", branches)

    def sequence(self):
        items = []
        while self.i < len(self.src) and self.src[self.i] not in "|)":
            items.append(self.quantified())
        return ("cat", items)

    def quantifier(self) -> Optional[tuple[int, Optional[int]]]:
        c = self.peek()
        if c in ("*", "+", "?"):
            self.i += 1
            return {"*": (0, None), "+": (1, None), "?": (0, 1)}[c]
        if c == "{":
            m = re.compile(r"\{(\d+)(,(\d*))?\}").match(self.src, self.i)
            if not m:
                raise self.fail("'{' that does not start a quantifier")
            self.i = m.end()
            lo = int(m.group(1))
            hi = lo if m.group(2) is None else (int(m.group(3)) if m.group(3) else None)
            if hi is not None and hi < lo:
                raise self.fail("quantifier {n,m} with m < n")
            if (hi if hi is not None else lo) > 1000:
                raise self.fail("quantifier bound above 1000")
            return lo, hi
        return None

    def quantified(self):
        atom = self.atom()
        while True:
            q = self.quantifier()
            if q is None:
                return atom
            if self.peek() == "?":
                self.i += 1          # lazy: same language for a yes/no match
            if atom[0] in ("start", "end"):
                raise self.fail("quantified anchor")
            atom = ("repeat", atom, q[0], q[1])

    def atom(self):
        c = self.src[self.i]
        if c == "(":
            self.i += 1
            if self.src.startswith("?:", self.i):
                self.i += 2
            elif self.peek() == "?":
                raise self.fail("lookaround or named group")
            node = self.alternation()
            if self.peek() != ")":
                raise self.fail("missing ')'")
            self.i += 1
            return node
        if c == "[":
            return self.char_class()
        if c == ".":
            self.i += 1
            return ("class", True, list(_LINE_TERMINATORS))
        if c == "^":
            self.i += 1
            return ("start",)
        if c == "$":
            self.i += 1
            return ("end",)
        if c in "*+?{":
            raise self.fail(f"nothing to repeat before {c!r}")
        if c == "\\":
            return self.escape(in_class=False)
        self.i += 1
        cp = ord(c)
        return ("class", False, [(cp, cp)])

    def _hex(self, n: int) -> int:
        digits = self.src[self.i:self.i + n]
        if len(digits) != n or not re.fullmatch(r"[0-9A-Fa-f]+", digits):
            raise self.fail("bad hexadecimal escape")
        self.i += n
        return int(digits, 16)

    def escape(self, in_class: bool):
        """Parse an escape at self.i (the backslash); return a class node."""
        self.i += 1
        if self.i >= len(self.src):
            raise self.fail("trailing backslash")
        c = self.src[self.i]
        self.i += 1
        sets = {"d": _DIGIT, "w": _WORD, "s": _SPACE}
        if c in sets:
            return ("class", False, list(sets[c]))
        if c in "DWS":
            if in_class:
                raise self.fail(f"\\{c} inside a character class")
            return ("class", True, list(sets[c.lower()]))
        simple = {"t": 0x09, "n": 0x0A, "v": 0x0B, "f": 0x0C, "r": 0x0D}
        if c in simple:
            cp = simple[c]
        elif c == "0":
            if self.peek().isdigit():
                raise self.fail("octal escape")
            cp = 0
        elif c == "x":
            cp = self._hex(2)
        elif c == "u":
            if self.peek() == "{":
                end = self.src.find("}", self.i)
                if end < 0:
                    raise self.fail("unterminated \\u{...}")
                body = self.src[self.i + 1:end]
                if not re.fullmatch(r"[0-9A-Fa-f]{1,6}", body) or int(body, 16) > _MAX_CODE_POINT:
                    raise self.fail("bad \\u{...} escape")
                cp, self.i = int(body, 16), end + 1
            else:
                cp = self._hex(4)
        elif c == "b" and in_class:
            cp = 0x08
        elif c.isalnum():
            raise self.fail(f"unsupported escape \\{c}")
        else:
            cp = ord(c)              # escaped punctuation: a literal
        return ("class", False, [(cp, cp)])

    def char_class(self):
        self.i += 1                  # '['
        negated = self.peek() == "^"
        if negated:
            self.i += 1
        ranges: list[tuple[int, int]] = []

        def single() -> tuple[bool, list[tuple[int, int]]]:
            """One class atom: (is_single_char, ranges)."""
            if self.peek() == "\\":
                node = self.escape(in_class=True)
                rs = node[2]
                return (len(rs) == 1 and rs[0][0] == rs[0][1]), rs
            ch = self.src[self.i]
            self.i += 1
            return True, [(ord(ch), ord(ch))]

        first = True
        while True:
            if self.i >= len(self.src):
                raise self.fail("unterminated character class")
            if self.peek() == "]" and not first:
                self.i += 1
                break
            if self.peek() == "]" and first:
                # "[]" matches nothing and "[^]" anything in ECMA-262.
                self.i += 1
                return ("class", not negated, [(0, _MAX_CODE_POINT)])
            first = False
            is_char, lo_rs = single()
            if (is_char and self.peek() == "-" and self.i + 1 < len(self.src)
                    and self.src[self.i + 1] != "]"):
                self.i += 1
                is_char2, hi_rs = single()
                if not is_char2:
                    raise self.fail("class escape as a range bound")
                lo, hi = lo_rs[0][0], hi_rs[0][0]
                if hi < lo:
                    raise self.fail("character range out of order")
                ranges.append((lo, hi))
            else:
                ranges.extend(lo_rs)
        return ("class", negated, _merge_ranges(ranges))


def compile_regex(source: str) -> list[tuple]:
    """A Pike-VM program for ``source``: a list of (op, x, y) where Class /
    NotClass carry a list of (lo, hi) code point ranges in x, Split carries two
    targets, Jump one, and LineStart / LineEnd / Match none."""
    tree = _RegexParser(source).parse()
    prog: list[list] = []

    def emit(node) -> None:
        tag = node[0]
        if tag == "class":
            negated, ranges = node[1], _merge_ranges(node[2])
            prog.append(["NotClass" if negated else "Class", ranges, None])
        elif tag == "start":
            prog.append(["LineStart", None, None])
        elif tag == "end":
            prog.append(["LineEnd", None, None])
        elif tag == "cat":
            for item in node[1]:
                emit(item)
        elif tag == "alt":
            jumps = []
            branches = node[1]
            for k, branch in enumerate(branches):
                if k < len(branches) - 1:
                    split = len(prog)
                    prog.append(["Split", split + 1, None])
                    emit(branch)
                    jumps.append(len(prog))
                    prog.append(["Jump", None, None])
                    prog[split][2] = len(prog)
                else:
                    emit(branch)
            for j in jumps:
                prog[j][1] = len(prog)
        elif tag == "repeat":
            body, lo, hi = node[1], node[2], node[3]
            for _ in range(lo):
                emit(body)
            if hi is None:
                split = len(prog)
                prog.append(["Split", split + 1, None])
                emit(body)
                prog.append(["Jump", split, None])
                prog[split][2] = len(prog)
            else:
                splits = []
                for _ in range(hi - lo):
                    splits.append(len(prog))
                    prog.append(["Split", len(prog) + 1, None])
                    emit(body)
                for s in splits:
                    prog[s][2] = len(prog)
        else:  # pragma: no cover - parser invariant
            raise GenerationError(f"pattern {source!r}: internal error ({tag})")
        if len(prog) > _MAX_RX_INSTRUCTIONS:
            raise GenerationError(f"pattern {source!r}: compiles to more than "
                                  f"{_MAX_RX_INSTRUCTIONS} instructions")

    emit(tree)
    prog.append(["Match", None, None])
    return [tuple(p) for p in prog]


# --- schema compiler ------------------------------------------------------------

class SchemaCompiler:
    """Compile the schema into nodes, ops and pools (see OPCODES)."""

    def __init__(self, schema: dict) -> None:
        self.schema = schema
        self.defs: dict = schema.get("$defs", {})
        self.nodes: list[Optional[list[tuple[int, int, int, int]]]] = []
        self.node_origin: list[str] = []
        self.strings = _Pool()
        self.numbers = _Pool()
        self.values = _Pool()
        self.lists: list[int] = []
        self.pairs: list[int] = []
        self.triples: list[int] = []
        self.regexes = _Pool()        # source -> index; programs in rx_programs
        self.rx_programs: list[list[tuple]] = []
        self.def_node: dict[str, int] = {}
        # Node 0 is the root; nodes 1..N are the $defs in schema order.
        self.root = self._reserve("#")
        for name in self.defs:
            self.def_node[name] = self._reserve(f"#/$defs/{name}")
        self._fill(self.root, {k: v for k, v in schema.items() if k != "$defs"}, "#")
        for name, sub in self.defs.items():
            self._fill(self.def_node[name], sub, f"#/$defs/{name}")

    # pools -----------------------------------------------------------------
    def _reserve(self, origin: str) -> int:
        self.nodes.append(None)
        self.node_origin.append(origin)
        return len(self.nodes) - 1

    def _string(self, s: str) -> int:
        return self.strings.add(s)

    def _number(self, x: Any, where: str) -> int:
        if isinstance(x, bool) or not isinstance(x, (int, float)):
            raise GenerationError(f"{where}: expected a number, got {x!r}")
        return self.numbers.add(float(x))

    def _value(self, v: Any) -> int:
        text = json.dumps(v, separators=(",", ":"), ensure_ascii=True)
        return self.values.add(text)

    def _list(self, items: list[int]) -> tuple[int, int]:
        start = len(self.lists)
        self.lists.extend(items)
        return start, len(items)

    def _pairs(self, pairs: list[tuple[int, int]]) -> tuple[int, int]:
        """Store (key, node) pairs contiguously. The nodes are compiled first,
        and compiling them stores their own pairs, so the caller builds the
        whole list before this runs."""
        start = len(self.pairs)
        for key, node in pairs:
            self.pairs.extend([key, node])
        return start, len(pairs)

    def _regex(self, source: str, where: str) -> int:
        if not isinstance(source, str):
            raise GenerationError(f"{where}: a pattern must be a string")
        before = len(self.regexes.items)
        idx = self.regexes.add(source)
        if idx == before:
            self.rx_programs.append(compile_regex(source))
        return idx

    @staticmethod
    def _count(x: Any, where: str) -> int:
        if isinstance(x, bool) or not isinstance(x, int) or x < 0 or x > 2**31 - 1:
            raise GenerationError(f"{where}: expected a non-negative integer, got {x!r}")
        return x

    # compilation --------------------------------------------------------------
    def compile(self, sub: Any, where: str) -> int:
        idx = self._reserve(where)
        self._fill(idx, sub, where)
        return idx

    def _fill(self, idx: int, sub: Any, where: str) -> None:
        ops: list[tuple[int, int, int, int]] = []
        self.nodes[idx] = ops        # placeholder against recursion
        if sub is True:
            return
        if sub is False:
            ops.append((OP["False"], 0, 0, 0))
            return
        if not isinstance(sub, dict):
            raise GenerationError(f"{where}: a schema must be an object or a boolean")
        for key, val in sub.items():
            at = f"{where}/{key}"
            if key in ANNOTATIONS or key in SIBLING_KEYWORDS:
                continue
            if key == "$defs":
                raise GenerationError(f"{at}: $defs is supported at the root only")
            op = self._op(key, val, sub, at)
            if op is not None:
                ops.append(op)

    def _nodes(self, items: Any, at: str) -> tuple[int, int]:
        if not isinstance(items, list) or not items:
            raise GenerationError(f"{at}: expected a non-empty array of schemas")
        return self._list([self.compile(s, f"{at}/{i}") for i, s in enumerate(items)])

    def _op(self, key: str, val: Any, sub: dict, at: str):
        if key == "type":
            names = [val] if isinstance(val, str) else val
            if not isinstance(names, list) or not names or any(n not in TYPE_BITS for n in names):
                raise GenerationError(f"{at}: bad type {val!r}")
            mask = 0
            for n in names:
                mask |= TYPE_BITS[n]
            return (OP["Type"], mask, 0, 0)
        if key == "const":
            return (OP["Const"], self._value(val), 0, 0)
        if key == "enum":
            if not isinstance(val, list) or not val:
                raise GenerationError(f"{at}: enum must be a non-empty array")
            start, n = self._list([self._value(v) for v in val])
            return (OP["Enum"], start, n, 0)
        if key == "$ref":
            m = re.fullmatch(r"#/\$defs/([^/~]+)", val) if isinstance(val, str) else None
            if not m or m.group(1) not in self.defs:
                raise GenerationError(f"{at}: only references to #/$defs/<name> "
                                      f"entries are supported, got {val!r}")
            return (OP["Ref"], self.def_node[m.group(1)], 0, 0)
        if key in ("allOf", "anyOf", "oneOf"):
            start, n = self._nodes(val, at)
            return (OP[key[0].upper() + key[1:]], start, n, 0)
        if key == "not":
            return (OP["Not"], self.compile(val, at), 0, 0)
        if key == "if":
            cond = self.compile(val, at)
            then = self.compile(sub["then"], at[:-2] + "then") if "then" in sub else -1
            other = self.compile(sub["else"], at[:-2] + "else") if "else" in sub else -1
            return (OP["If"], cond, then, other)
        if key == "properties":
            if not isinstance(val, dict):
                raise GenerationError(f"{at}: properties must be an object")
            return (OP["Properties"], *self._pairs(
                [(self._string(name), self.compile(s, f"{at}/{name}"))
                 for name, s in val.items()]), 0)
        if key == "patternProperties":
            if not isinstance(val, dict):
                raise GenerationError(f"{at}: patternProperties must be an object")
            return (OP["PatternProperties"], *self._pairs(
                [(self._regex(pattern, at), self.compile(s, f"{at}/{pattern}"))
                 for pattern, s in val.items()]), 0)
        if key == "additionalProperties":
            if val is True:
                return None
            node = -1 if val is False else self.compile(val, at)
            return (OP["AdditionalProperties"], node, 0, 0)
        if key == "required":
            if not isinstance(val, list) or not all(isinstance(v, str) for v in val):
                raise GenerationError(f"{at}: required must be an array of strings")
            start, n = self._list([self._string(v) for v in val])
            return (OP["Required"], start, n, 0)
        if key == "dependentRequired":
            if not isinstance(val, dict):
                raise GenerationError(f"{at}: dependentRequired must be an object")
            triples = []
            for name, deps in val.items():
                if not isinstance(deps, list) or not all(isinstance(d, str) for d in deps):
                    raise GenerationError(f"{at}/{name}: expected an array of strings")
                lst, n = self._list([self._string(d) for d in deps])
                triples.extend([self._string(name), lst, n])
            start = len(self.triples)
            self.triples.extend(triples)
            return (OP["DependentRequired"], start, len(val), 0)
        if key == "dependentSchemas":
            if not isinstance(val, dict):
                raise GenerationError(f"{at}: dependentSchemas must be an object")
            return (OP["DependentSchemas"], *self._pairs(
                [(self._string(name), self.compile(s, f"{at}/{name}"))
                 for name, s in val.items()]), 0)
        if key == "propertyNames":
            return (OP["PropertyNames"], self.compile(val, at), 0, 0)
        if key in ("minProperties", "maxProperties", "minItems", "maxItems",
                   "minLength", "maxLength"):
            return (OP[key[0].upper() + key[1:]], self._count(val, at), 0, 0)
        if key == "prefixItems":
            start, n = self._nodes(val, at)
            return (OP["PrefixItems"], start, n, 0)
        if key == "items":
            if isinstance(val, list):
                raise GenerationError(f"{at}: array-form items is not 2020-12; "
                                      f"use prefixItems")
            prefix = sub.get("prefixItems", [])
            node = -1 if val is False else self.compile(val, at)
            return (OP["Items"], node, len(prefix) if isinstance(prefix, list) else 0, 0)
        if key == "contains":
            lo = self._count(sub.get("minContains", 1), at[:-8] + "minContains")
            hi = sub.get("maxContains")
            hi = -1 if hi is None else self._count(hi, at[:-8] + "maxContains")
            return (OP["Contains"], self.compile(val, at), lo, hi)
        if key == "uniqueItems":
            if not isinstance(val, bool):
                raise GenerationError(f"{at}: uniqueItems must be a boolean")
            return (OP["UniqueItems"], 0, 0, 0) if val else None
        if key in ("minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum",
                   "multipleOf"):
            number = self._number(val, at)
            if key == "multipleOf" and not val > 0:
                raise GenerationError(f"{at}: multipleOf must be positive")
            return (OP[key[0].upper() + key[1:]], number, 0, 0)
        if key == "pattern":
            return (OP["Pattern"], self._regex(val, at), 0, 0)
        raise GenerationError(
            f"{at}: JSON Schema keyword {key!r} is not supported by the generated "
            f"checkers; extend OPCODES in scripts/gen_kinds.py and both "
            f"interpreters (cpp/src/qvf_schema_check.hpp, js/src/schemaCheck.ts)")

# --- kind tables ----------------------------------------------------------------

class SchemaModel:
    """Everything the generated tables say, derived from the inputs."""

    def __init__(self, schema: dict, registry: dict, spec_text: str) -> None:
        self.schema = schema
        self.defs: dict = schema["$defs"]
        self.registry = registry
        self.schema_id: str = schema.get("$id", "")
        self.dialect: str = schema.get("$schema", "")
        version = schema.get("properties", {}).get("qvf_version", {}).get("const")
        if not isinstance(version, int):
            raise GenerationError("properties.qvf_version has no integer const")
        self.qvf_version = version
        self.readable_versions = self._int_list(registry, "readable_versions")
        self.producible_versions = self._int_list(registry, "producible_versions")
        self.dtypes: list[str] = list(self.defs["NumpyDtype"]["enum"])
        self.kinds = self._kinds()
        self.payload_defs = self._payload_defs()
        self.units, self.legacy_units = self._units()
        self.fixed_units = self._fixed_units()
        self.finding_codes = self._finding_codes(spec_text)

    @staticmethod
    def _int_list(registry: dict, key: str) -> list[int]:
        val = registry.get(key)
        if not isinstance(val, list) or not all(isinstance(v, int) and not isinstance(v, bool)
                                                for v in val):
            raise GenerationError(f"registry.json: {key} must be an array of integers")
        return val

    def _ref(self, node: Any) -> Any:
        while isinstance(node, dict) and "$ref" in node and len(node) == 1:
            node = self.defs[node["$ref"].rsplit("/", 1)[1]]
        return node

    # member analysis --------------------------------------------------------
    def _member(self, node: Any) -> dict:
        """Constraints a member spec schema places on format, dtype and rank:
        {fmt, typed (dtype required), dtypes (set or None), lo, hi (None = no
        bound)}."""
        info = {"fmt": None, "typed": False, "dtypes": None, "lo": 0, "hi": None}
        if not isinstance(node, dict):
            return info

        def merge(a: dict, b: dict) -> dict:
            if a["fmt"] and b["fmt"] and a["fmt"] != b["fmt"]:
                raise GenerationError("member schema with contradictory formats")
            dtypes = (a["dtypes"] if b["dtypes"] is None else
                      b["dtypes"] if a["dtypes"] is None else a["dtypes"] & b["dtypes"])
            his = [h for h in (a["hi"], b["hi"]) if h is not None]
            return {"fmt": a["fmt"] or b["fmt"], "typed": a["typed"] or b["typed"],
                    "dtypes": dtypes, "lo": max(a["lo"], b["lo"]),
                    "hi": min(his) if his else None}

        def union(alts: list[dict]) -> dict:
            fmts = {a["fmt"] for a in alts}
            if len(fmts) != 1:
                raise GenerationError("member schema alternatives of different formats")
            dts = [a["dtypes"] for a in alts]
            return {"fmt": fmts.pop(), "typed": all(a["typed"] for a in alts),
                    "dtypes": None if any(d is None for d in dts) else set().union(*dts),
                    "lo": min(a["lo"] for a in alts),
                    "hi": None if any(a["hi"] is None for a in alts)
                    else max(a["hi"] for a in alts)}

        if "$ref" in node:
            info = merge(info, self._member(self.defs[node["$ref"].rsplit("/", 1)[1]]))
        for part in node.get("allOf", []):
            info = merge(info, self._member(part))
        for key in ("anyOf", "oneOf"):
            if key in node:
                info = merge(info, union([self._member(p) for p in node[key]]))
        props = node.get("properties", {})
        if "format" in props:
            fmt = self._ref(props["format"]).get("const")
            if fmt not in ("json", "binary"):
                raise GenerationError(f"member format const {fmt!r} is neither json nor binary")
            info = merge(info, {"fmt": fmt, "typed": False, "dtypes": None, "lo": 0, "hi": None})
        if "dtype" in props:
            info = merge(info, {"fmt": None, "typed": False,
                                "dtypes": self._dtype_set(props["dtype"]), "lo": 0, "hi": None})
        if "shape" in props:
            lo, hi = self._rank_range(props["shape"])
            info = merge(info, {"fmt": None, "typed": False, "dtypes": None, "lo": lo, "hi": hi})
        if "dtype" in node.get("required", []):
            info["typed"] = True
        return info

    def _dtype_set(self, node: Any) -> Optional[set]:
        node = self._ref(node)
        out: Optional[set] = None
        if "$ref" in node:
            out = self._dtype_set({"$ref": node["$ref"]})
        if "const" in node:
            out = {node["const"]} if out is None else out & {node["const"]}
        if "enum" in node:
            out = set(node["enum"]) if out is None else out & set(node["enum"])
        for part in node.get("allOf", []):
            sub = self._dtype_set(part)
            out = sub if out is None else (out if sub is None else out & sub)
        return out

    def _rank_range(self, node: Any) -> tuple[int, Optional[int]]:
        node = self._ref(node)
        lo, hi = node.get("minItems", 0), node.get("maxItems")
        for key in ("oneOf", "anyOf"):
            if key in node:
                alts = [self._rank_range(p) for p in node[key]]
                alo = min(a[0] for a in alts)
                ahi = None if any(a[1] is None for a in alts) else max(a[1] for a in alts)
                lo = max(lo, alo)
                hi = ahi if hi is None else (hi if ahi is None else min(hi, ahi))
        return lo, hi

    def _role(self, name: str, node: Any, required: bool, pattern: bool) -> dict:
        info = self._member(node)
        if info["fmt"] is None:
            raise GenerationError(f"member role {name!r}: cannot tell its format")
        if info["fmt"] == "json":
            fmt, dtypes, lo, hi = "json", [], -1, -1
        elif not info["typed"]:
            fmt, dtypes, lo, hi = "opaque", [], -1, -1
        else:
            allowed = info["dtypes"] if info["dtypes"] is not None else set(self.dtypes)
            unknown = allowed - set(self.dtypes)
            if unknown:
                raise GenerationError(f"member role {name!r}: unknown dtypes {sorted(unknown)}")
            fmt = "binary"
            dtypes = [d for d in self.dtypes if d in allowed]
            lo, hi = info["lo"], (-1 if info["hi"] is None else info["hi"])
        return {"role": name, "required": required, "format": fmt, "dtypes": dtypes,
                "min_rank": lo, "max_rank": hi, "pattern": pattern, "payload_def": ""}

    def _kinds(self) -> list[dict]:
        by_kind: dict[str, dict] = {}
        for branch in self.defs["Section"]["oneOf"]:
            name = branch["$ref"].rsplit("/", 1)[1]
            sec = self.defs[name]
            kind = sec.get("properties", {}).get("kind", {}).get("const")
            if kind is None:
                continue                      # the vendor branch: a pattern
            members = sec["properties"].get("members", {})
            required = set(members.get("required", []))
            roles = [self._role(r, s, r in required, False)
                     for r, s in members.get("properties", {}).items()]
            roles += [self._role(p, s, False, True)
                      for p, s in members.get("patternProperties", {}).items()]
            by_kind[kind] = {"kind": kind, "def": name, "roles": roles,
                             "allow_extra_members": members.get("additionalProperties",
                                                                True) is not False}
        reg = self.registry.get("canonical_kinds")
        if not isinstance(reg, list) or not all(isinstance(k, str) for k in reg):
            raise GenerationError("registry.json: canonical_kinds must be an array of strings")
        missing, extra = set(by_kind) - set(reg), set(reg) - set(by_kind)
        if missing or extra or len(reg) != len(set(reg)):
            raise GenerationError(
                f"registry.json canonical_kinds disagrees with the schema's Section "
                f"branches (missing: {sorted(missing)}, extra: {sorted(extra)}); "
                f"fix the registry first")
        return [by_kind[k] for k in reg]

    def _payload_defs(self) -> list[tuple[str, str, str]]:
        kinds = {k["kind"]: k for k in self.kinds}
        rows = []
        for (kind, role), defname in PAYLOAD_DEFS.items():
            if defname not in self.defs:
                raise GenerationError(f"PAYLOAD_DEFS: ({kind!r}, {role!r}) names "
                                      f"$defs/{defname}, which the schema lacks")
            if kind not in kinds:
                raise GenerationError(f"PAYLOAD_DEFS: {kind!r} is not a canonical kind")
            roles = {r["role"]: r for r in kinds[kind]["roles"] if not r["pattern"]}
            if role not in roles or roles[role]["format"] != "json":
                raise GenerationError(f"PAYLOAD_DEFS: {kind!r} has no JSON member "
                                      f"role {role!r}")
            roles[role]["payload_def"] = defname
            rows.append((kind, role, defname))
        unused = [n for n in self.defs if n.endswith("Payload")
                  and n not in PAYLOAD_DEFS.values()]
        if unused:
            raise GenerationError(
                f"$defs {unused} look like payload definitions but no row of "
                f"PAYLOAD_DEFS in scripts/gen_kinds.py names them; add the "
                f"(kind, role) that carries each")
        return rows

    def _units(self) -> tuple[list[str], list[str]]:
        units = self.defs["UnitName"]["enum"]
        legacy = self.defs["LegacyUnitName"]["enum"]
        if set(legacy) != set(LEGACY_CANONICAL) or not set(LEGACY_CANONICAL.values()) <= set(units):
            raise GenerationError(
                f"$defs/LegacyUnitName {legacy!r} disagrees with LEGACY_CANONICAL in "
                f"scripts/gen_kinds.py; map every legacy spelling to a unit name")
        if len(set(units)) != len(units):
            raise GenerationError("$defs/UnitName has duplicates")
        return list(units), list(legacy)

    def _fixed_units(self) -> list[tuple[str, list[tuple[str, str]]]]:
        out = []
        for name in self.defs:
            fixed: dict[str, str] = {}

            def visit(n: str) -> None:
                node = self.defs[n]
                for part in node.get("allOf", []):
                    ref = part.get("$ref", "") if isinstance(part, dict) else ""
                    if ref.startswith("#/$defs/"):
                        visit(ref[len("#/$defs/"):])
                units = node.get("properties", {}).get("units", {})
                if isinstance(units, dict):
                    for key, spec in units.get("properties", {}).items():
                        if isinstance(spec, dict) and "const" in spec:
                            fixed[key] = spec["const"]

            visit(name)
            if fixed:
                out.append((name, list(fixed.items())))
        return out

    @staticmethod
    def _finding_codes(spec_text: str) -> list[tuple[str, str]]:
        if "## Appendix B." not in spec_text:
            raise GenerationError("spec/qvf-format-spec.md has no '## Appendix B.'")
        appendix = spec_text.split("## Appendix B.", 1)[1]
        rows = re.findall(r"^\| `([EW]_[A-Z0-9_]+)` \| (error|warning) \|", appendix, re.M)
        if not rows or len({c for c, _ in rows}) != len(rows):
            raise GenerationError("Appendix B: no finding codes, or duplicates")
        for code, severity in rows:
            if code[0] != ("E" if severity == "error" else "W"):
                raise GenerationError(f"Appendix B: {code} has severity {severity}")
        return rows


def unit_identifier(name: str) -> str:
    if name in UNIT_IDENTIFIERS:
        return UNIT_IDENTIFIERS[name]
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", name) if p]
    ident = "".join(p[0].upper() + p[1:] for p in parts)
    if not ident or not ident[0].isalpha():
        ident = "Unit" + ident
    return ident


# --- rendering helpers ------------------------------------------------------------

def cpp_string(s: str) -> str:
    """A C++ string literal; non-ASCII and control bytes as octal escapes."""
    out = ['"']
    for b in s.encode("utf-8"):
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif 0x20 <= b < 0x7F and b != 0x3F:   # '?' escaped: no trigraphs
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    out.append('"')
    return "".join(out)


def ts_string(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)


def py_string(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)


def cpp_double(x: float) -> str:
    text = repr(float(x))
    if text in ("inf", "-inf", "nan"):
        raise GenerationError(f"non-finite number {x!r} in the schema")
    if "." not in text and "e" not in text:
        text += ".0"
    return text


def ts_number(x: float) -> str:
    text = repr(float(x))
    return text[:-2] if text.endswith(".0") else text


def wrap(items: list[str], indent: str, width: int = 96) -> list[str]:
    """Comma-separated items wrapped into lines no wider than ``width``."""
    lines, cur = [], indent
    for item in items:
        piece = item + ","
        if len(cur) + len(piece) + 1 > width and cur.strip():
            lines.append(cur.rstrip())
            cur = indent
        cur += piece + " "
    if cur.strip():
        lines.append(cur.rstrip())
    return lines


