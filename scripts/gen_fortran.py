#!/usr/bin/env python3
"""Generate ISO_C_BINDING declarations from the deliberately small public C ABI.

Pointers are raw c_ptr values (including pointer-to-pointer output addresses).
Fail closed on new C syntax/types rather than emitting a guessed signature.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADERS = ['qvf_c.h', 'c_api.h']
SCALARS = {'int': 'integer(c_int)', 'unsigned': 'integer(c_int)',
           'qvf_status': 'integer(c_int)', 'size_t': 'integer(c_size_t)',
           'uint64_t': 'integer(c_int64_t)', 'int64_t': 'integer(c_int64_t)',
           'double': 'real(c_double)'}


def generate():
    text = '\n'.join((ROOT/'cpp/include/qvf'/p).read_text() for p in HEADERS)
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    kinds = re.findall(r'QVF_C_KIND\((\w+),', (ROOT/'cpp/include/qvf/c_kinds_generated.h').read_text())
    text = re.sub(r'#define QVF_C_KIND\(name, kind\).*?\n', '', text)
    text = text.replace('#include "qvf/c_kinds_generated.h"', '\n'.join(
        f'QVF_API qvf_status qvf_writer_add_{name}(qvf_writer*, const qvf_section_input*);' for name in kinds))
    enums = re.findall(r'(?:typedef\s+)?enum(?:\s+\w+)?\s*\{([^}]+)\}\s*(\w+)?\s*;', text)
    types = dict(SCALARS)
    for _, name in enums:
        if name:
            types[name] = 'integer(c_int)'
    structs = re.findall(r'typedef struct (\w+)\s*\{([^}]+)\}\s*\w+\s*;', text)
    for name, _ in structs:
        types[name] = f'type({name}_t)'

    def ftype(ctype):
        ctype = re.sub(r'\bconst\b', '', ctype).strip()
        if '*' in ctype or '[' in ctype:
            return 'type(c_ptr)'
        if ctype == 'qvf_chunk_callback':
            return 'type(c_funptr)'
        return types[ctype]

    lines = ['! Generated by scripts/gen_fortran.py; do not edit.',
             '! License: Apache-2.0.', 'module qvf_c', '  use, intrinsic :: iso_c_binding',
             '  implicit none',
             '  integer(c_int), parameter :: QVF_ABI_VERSION = ' + re.search(r'#define QVF_ABI_VERSION (\d+)', text)[1]]
    for body, _ in enums:
        for entry in body.split(','):
            name, value = entry.strip().split('=')
            lines.append(f'  integer(c_int), parameter :: {name.strip()} = {int(value)}')
    for name, body in structs:
        lines.append(f'  type, bind(C) :: {name}_t')
        for field in body.split(';'):
            if not field.strip():
                continue
            parts = field.strip().split(',')
            match = re.fullmatch(r'(.+?[\s*])(\w+)', parts[0].strip())
            if not match:
                raise ValueError(f'Unsupported field {field!r}')
            ctype, first = match.groups()
            lines.append(f'    {ftype(ctype)} :: {first}')
            for extra in parts[1:]:
                if not re.fullmatch(r'\s*\w+\s*', extra):
                    raise ValueError(f'Unsupported field {extra!r}')
                lines.append(f'    {ftype(ctype)} :: {extra.strip()}')
        lines.append(f'  end type {name}_t')
    lines.append('  interface')
    functions = re.findall(r'QVF_API\s+([\w\s*]+?)\s+(qvf_\w+)\(([^;]+)\);', text, flags=re.S)
    if len(functions) != text.count('QVF_API'):
        raise ValueError('Unparsed C function declaration')
    for result, name, arguments in functions:
        args = [] if arguments.strip() == 'void' else arguments.split(',')
        argtypes = []
        for arg in args:
            arg = re.sub(r'\s+', ' ', arg.strip())
            arg = re.sub(r'\[[^]]*\]', '*', arg)
            # The facade includes unnamed arguments. Strip a name only when
            # the complete token sequence is not itself a known C type.
            base = re.sub(r'\bconst\b|\*', '', arg).strip()
            if base not in types and base not in {'qvf_writer', 'qvf_reader', 'qvf_editor', 'qvf_report', 'void', 'char', 'qvf_chunk_callback'}:
                arg = re.sub(r'\b\w+\s*(\*)?$', lambda m: m[1] or '', arg).strip()
            argtypes.append(ftype(arg))
        identifiers = [f'a{i+1}' for i in range(len(args))]
        sub = result.strip() == 'void'
        keyword = 'subroutine' if sub else 'function'
        suffix = '' if sub else ' result(value)'
        lines.append(f'    {keyword} c_{name}( &')
        for start in range(0, len(identifiers), 6):
            group = ', '.join(identifiers[start:start+6])
            lines.append('        ' + group + (', &' if start+6 < len(identifiers) else ') &'))
        if not identifiers:
            lines.append('        ) &')
        lines.append(f'        bind(C, name="{name}"){suffix}')
        lines.append('      import')
        for ident, typ in zip(identifiers, argtypes):
            lines.append(f'      {typ}, value :: {ident}')
        if not sub:
            lines.append(f'      {ftype(result)} :: value')
        lines.append(f'    end {keyword} c_{name}')
    lines.extend(['  end interface', 'end module qvf_c', ''])
    if any(len(line)>132 for line in lines):
        raise ValueError('Generated line exceeds portable free-form limit')
    return '\n'.join(lines), len(functions)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, count = generate()
    target = ROOT/'fortran/qvf_c.f90'
    if args.check:
        if not target.exists() or target.read_text() != content:
            parser.exit(1, 'Fortran C bindings are stale; run scripts/gen_fortran.py\n')
    else:
        target.write_text(content)
    print(f'{count} C ABI bindings current')


if __name__ == '__main__':
    main()
